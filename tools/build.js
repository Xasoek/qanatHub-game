import { readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { TEXT } from "../src/text.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const index = new URL("../index.html", import.meta.url);

export async function renderIndex() {
  const { outputFiles, metafile } = await build({
    absWorkingDir: root,
    entryPoints: { game: "src/style.css", app: "src/main.js" },
    outdir: ".",
    platform: "browser",
    format: "iife",
    bundle: true,
    minifyWhitespace: true,
    minifySyntax: true,
    write: false,
    metafile: true,
    target: "es2022",
    charset: "utf8",
    legalComments: "inline",
  });
  for (const output of Object.values(metafile.outputs)) {
    for (const asset of output.imports) {
      if (!asset.path.startsWith("data:") && !asset.path.startsWith("#")) {
        throw new Error(`Bundle requires an external asset: ${asset.path}`);
      }
    }
  }
  if (outputFiles.length !== 2) throw new Error("Expected exactly one JS file and one CSS file");
  const js = outputFiles.find((file) => basename(file.path) === "app.js").text;
  const css = outputFiles.find((file) => basename(file.path) === "game.css").text;
  const title = TEXT.en.game.title.replaceAll("&", "&amp;").replaceAll("<", "&lt;");

  return `<!doctype html>
<!-- Generated by npm run build -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<style>
${css.trimEnd()}
</style>
</head>
<body>
<main id="game"></main>
<script>
${js.trimEnd()}
</script>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = await renderIndex();
  if (process.argv.includes("--check")) {
    if (await readFile(index, "utf8") !== html) {
      throw new Error("index.html is out of date. Run npm run build and commit the result.");
    }
    console.log("index.html matches the sources");
  } else {
    await writeFile(index, html);
    console.log("Built index.html");
  }
}
