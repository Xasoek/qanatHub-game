// Role 3: writes src/nasa-archive.js from real NASA DONKI data for 1–31 May 2024.
// Usage:
//   NASA_API_KEY=... node tools/donki-archive.js     downloads (the key never enters the repo)
//   node tools/donki-archive.js saved.json            uses a saved FLR or notifications response
// DONKI/FLR is tried first. When it fails (api.nasa.gov answers 404 for FLR since 2026-11),
// the flare notifications of the same month are used. Values are copied unchanged.
import { readFile, writeFile } from "node:fs/promises";
import { FLARE_FIELDS, extractFlares, flareClass } from "../src/data.js";

const startDate = "2024-05-01";
const endDate = "2024-05-31";
const target = new URL("../src/nasa-archive.js", import.meta.url);
const range = `startDate=${startDate}&endDate=${endDate}`;

async function getJson(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return response.json();
}

async function download() {
  const key = process.env.NASA_API_KEY || "DEMO_KEY";
  const sources = [
    ["DONKI/FLR", `https://kauai.ccmc.gsfc.nasa.gov/DONKI/WS/get/FLR?${range}`],
    ["DONKI/FLR", `https://api.nasa.gov/DONKI/FLR?${range}&api_key=${key}`],
    ["DONKI/notifications (flare notifications)",
      `https://api.nasa.gov/DONKI/notifications?${range}&type=FLR&api_key=${key}`],
  ];
  for (const [endpoint, url] of sources) {
    try {
      const body = await getJson(url);
      if (extractFlares(body).length) return { endpoint, body };
      console.warn(`${endpoint} @ ${new URL(url).host}: no flares`);
    } catch (error) {
      console.warn(`${endpoint} @ ${new URL(url).host}: ${error.message}`);
    }
  }
  throw new Error("DONKI is unreachable. Set NASA_API_KEY or pass a saved response file.");
}

const file = process.argv[2];
const { endpoint, body } = file
  ? { endpoint: undefined, body: JSON.parse(await readFile(file, "utf8")) }
  : await download();
const isNotifications = Array.isArray(body) && body.some((record) => "messageBody" in record);

const all = extractFlares(body);
const flares = all.filter((flare) => {
  const day = flare.beginTime.slice(0, 10);
  if (day >= startDate && day <= endDate) return true;
  console.warn(`Skipped ${flare.flrID}: starts outside May 2024`);
  return false;
});
if (!flares.length) throw new Error("No flares for May 2024 in the response");

// The class in each notification body must match the class in its title.
if (isNotifications) {
  for (const flare of flares) {
    const message = body.find((record) => record.messageID === flare.messageID);
    const title = message.messageBody.match(/Space Weather Notification - ([A-Z][\d.]+) Flare/)[1];
    if (title !== flare.classType) throw new Error(`${flare.flrID}: title ${title} ≠ body ${flare.classType}`);
  }
}
for (const flare of flares) {
  if (!flareClass(flare.classType)) throw new Error(`${flare.flrID}: bad classType ${flare.classType}`);
}

const archive = {
  endpoint: endpoint ?? (isNotifications ? "DONKI/notifications (flare notifications)" : "DONKI/FLR"),
  startDate,
  endDate,
  fetchedAt: new Date().toISOString().slice(0, 10),
  flares,
};
await writeFile(target, `// Generated by tools/donki-archive.js from NASA DONKI. Do not edit by hand.
// Kept fields: ${FLARE_FIELDS.join(", ")}. Values are copied as DONKI wrote them.
${isNotifications ? "// Notifications cover significant flares only (DONKI posts them for M5 and stronger).\n" : ""}export const ARCHIVE = ${JSON.stringify(archive, null, 2)};
`);
console.log(`Wrote ${flares.length} flares from ${archive.endpoint} to src/nasa-archive.js`);
