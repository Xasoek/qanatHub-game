// Role 3: writes src/nasa-archive.js from a real DONKI FLR response for 1–31 May 2024.
// Usage:
//   node tools/donki-archive.js path/to/FLR.json   (a response saved from the browser)
//   node tools/donki-archive.js                    (downloads it; NASA_API_KEY is optional)
// Values are copied unchanged; only the fields in FLARE_FIELDS are kept.
import { readFile, writeFile } from "node:fs/promises";
import { FLARE_FIELDS, pickFlare } from "../src/data.js";

const startDate = "2024-05-01";
const endDate = "2024-05-31";
const target = new URL("../src/nasa-archive.js", import.meta.url);

async function download() {
  const key = process.env.NASA_API_KEY || "DEMO_KEY";
  const urls = [
    `https://kauai.ccmc.gsfc.nasa.gov/DONKI/WS/get/FLR?startDate=${startDate}&endDate=${endDate}`,
    `https://api.nasa.gov/DONKI/FLR?startDate=${startDate}&endDate=${endDate}&api_key=${key}`,
  ];
  for (const url of urls) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      if (response.ok) return response.json();
      console.warn(`${new URL(url).host}: HTTP ${response.status}`);
    } catch (error) {
      console.warn(`${new URL(url).host}: ${error.message}`);
    }
  }
  throw new Error("DONKI is unreachable. Save the FLR response in a browser and pass the file path.");
}

const file = process.argv[2];
const body = file ? JSON.parse(await readFile(file, "utf8")) : await download();
if (!Array.isArray(body) || !body.length) throw new Error("Expected a non-empty DONKI FLR array");

const flares = body.map(pickFlare);
for (const flare of flares) {
  if (typeof flare.classType !== "string" || typeof flare.beginTime !== "string") {
    throw new Error(`Record without classType or beginTime: ${JSON.stringify(flare)}`);
  }
  const day = flare.beginTime.slice(0, 10);
  if (day < startDate || day > endDate) throw new Error(`Record outside May 2024: ${flare.beginTime}`);
}

const archive = {
  endpoint: "DONKI/FLR",
  startDate,
  endDate,
  fetchedAt: new Date().toISOString().slice(0, 10),
  flares,
};
await writeFile(target, `// Generated by tools/donki-archive.js from the NASA DONKI FLR response. Do not edit by hand.
// Kept fields: ${FLARE_FIELDS.join(", ")}.
export const ARCHIVE = ${JSON.stringify(archive, null, 2)};
`);
console.log(`Wrote ${flares.length} flares to src/nasa-archive.js`);
